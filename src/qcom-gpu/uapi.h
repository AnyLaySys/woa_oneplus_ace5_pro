#pragma once
#ifdef _KERNEL_MODE
typedef ULONG GPU_U32;
typedef ULONGLONG GPU_U64;
#else
#include <stdint.h>
typedef uint32_t GPU_U32;
typedef uint64_t GPU_U64;
#endif
#define GPU_UAPI_VERSION 4
#define GPU_MAX_BUFFERS 1024
#define GPU_MAX_BUFFER_SIZE 0x20000000
#define GPU_CLIENT_VA_BASE 0x100000000ULL
#define GPU_CLIENT_VA_SIZE 0x200000000ULL
#define GPU_CLIENT_VA_END (GPU_CLIENT_VA_BASE+GPU_CLIENT_VA_SIZE)
#define GPU_VA_END 0x400000000ULL
#define GPU_IOCTL_QUERY CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_DATA)
#define GPU_IOCTL_ALLOC CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_DATA|FILE_WRITE_DATA)
#define GPU_IOCTL_FREE CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_DATA|FILE_WRITE_DATA)
#define GPU_IOCTL_CLIENT_LEASE CTL_CODE(FILE_DEVICE_UNKNOWN,0x806,METHOD_BUFFERED,FILE_READ_DATA)
#define GPU_IOCTL_ALLOC_CACHED CTL_CODE(FILE_DEVICE_UNKNOWN,0x809,METHOD_BUFFERED,FILE_READ_DATA|FILE_WRITE_DATA)
#define GPU_IOCTL_CACHE CTL_CODE(FILE_DEVICE_UNKNOWN,0x80A,METHOD_BUFFERED,FILE_READ_DATA|FILE_WRITE_DATA)
#define GPU_IOCTL_SHARED_RETAIN CTL_CODE(FILE_DEVICE_UNKNOWN,0x80F,METHOD_BUFFERED,FILE_READ_DATA|FILE_WRITE_DATA)
#define GPU_IOCTL_SHARED_RELEASE CTL_CODE(FILE_DEVICE_UNKNOWN,0x810,METHOD_BUFFERED,FILE_WRITE_DATA)
typedef struct { GPU_U32 Version,Chip,Status; } GPU_INFO;
typedef struct { GPU_U32 Handle,Size; GPU_U64 Address,Map; } GPU_ALLOCATION;
typedef struct { GPU_U32 Handle,Offset,Words,Reserved; } GPU_SUBMIT;
typedef struct { GPU_U32 Handle,Offset,Size,Readback; } GPU_CACHE;
typedef struct { GPU_U64 Address,Size; } GPU_SHARED_IMPORT;

#define GPU_IOCTL_SPARSE_CAPS CTL_CODE(FILE_DEVICE_UNKNOWN,0x811,METHOD_BUFFERED,FILE_READ_DATA)
#define GPU_IOCTL_VA_RESERVE CTL_CODE(FILE_DEVICE_UNKNOWN,0x812,METHOD_BUFFERED,FILE_READ_DATA|FILE_WRITE_DATA)
#define GPU_IOCTL_VA_RELEASE CTL_CODE(FILE_DEVICE_UNKNOWN,0x813,METHOD_BUFFERED,FILE_WRITE_DATA)
#define GPU_IOCTL_VA_BIND CTL_CODE(FILE_DEVICE_UNKNOWN,0x814,METHOD_BUFFERED,FILE_READ_DATA|FILE_WRITE_DATA)
#define GPU_IOCTL_POWER_QUERY CTL_CODE(FILE_DEVICE_UNKNOWN,0x815,METHOD_BUFFERED,FILE_READ_DATA)
#define GPU_IOCTL_DISPLAY_QUERY CTL_CODE(FILE_DEVICE_UNKNOWN,0x816,METHOD_BUFFERED,FILE_READ_DATA)
#define GPU_IOCTL_FAULT_QUERY CTL_CODE(FILE_DEVICE_UNKNOWN,0x817,METHOD_BUFFERED,FILE_READ_DATA)
typedef struct {
    GPU_U32 Version,Size,Source,Bits,Syndrome0,Syndrome1,AddressLow,AddressHigh;
    GPU_U32 Submitted,Completed,WriteIndex,ReadIndex,GmuStatus,PowerStatus,ResetStage,ResetStatus;
} GPU_FAULT_INFO;
typedef struct {
    GPU_U32 Version,Size,Flags,Status,State,Queued,Applied,PendingFence,Completed,Submitted;
    GPU_U32 Line,Event,Done,Frame,InitialFrame,Flushed;
    GPU_U32 FailureState,FailureLine,FailureEvent,FailureDone,FailureFrame,FailureFlushed,Pitch,Period;
} GPU_DISPLAY_INFO;
typedef struct {
    GPU_U32 Version,Size,Flags,CurrentKhz,CeilingKhz,BusyPercent,TemperatureDci,CoolingBand,Status;
} GPU_POWER_INFO;
typedef struct { GPU_U64 Address,Size; GPU_U32 Flags,Reserved; } GPU_VA_RESERVE;
typedef struct { GPU_U64 Address,Size; GPU_U32 Handle,Reserved; } GPU_VA_ALLOCATION;
typedef struct { GPU_U32 Handle,Buffer; GPU_U64 Offset,BufferOffset,Size; } GPU_VA_BIND;
